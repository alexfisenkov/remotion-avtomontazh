#!/usr/bin/env node
// Проверяет монтажный лист по правилам ТЗ до того, как запускать рендер на 20+ минут.
// Запуск: node check-plan.mjs [путь до edit-plan.json]   (по умолчанию ./edit-plan.json)
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const путь = resolve(process.argv[2] ?? 'edit-plan.json');
let plan;
try {
  plan = JSON.parse(readFileSync(путь, 'utf8'));
} catch (e) {
  console.error(`Не читается монтажный лист ${путь}: ${e.message}`);
  process.exit(2);
}

const MIN_ON_SCREEN = 1.6; // с — меньше зритель не успевает прочитать
const MIN_GAP = 1.5; // с — иначе надписи «мигают» одна за другой
const проблемы = [];
const пометки = [];

const режим = (t) => plan.modes?.find((m) => t >= m.from && t < m.to)?.mode ?? null;
const cues = [...(plan.cues ?? [])].sort((a, b) => a.at - b.at);

if (!cues.length) // Пустой лист — стартовое состояние свежего проекта, а не ошибка: разметка ещё впереди.
  пометки.push('в листе пока нет ни одной надписи — это стартовое состояние, разметьте cues');
if (!plan.modes?.length) проблемы.push('не описаны modes — без них не проверить, где какой режим кадра');

for (const c of cues) {
  const длит = c.until - c.at;
  if (длит < MIN_ON_SCREEN) {
    проблемы.push(`${c.id}: на экране ${длит.toFixed(2)} с, минимум ${MIN_ON_SCREEN}`);
  }
  if (c.accent) {
    const попаданий = c.lines.filter((l) => l.includes(c.accent)).length;
    if (попаданий !== 1) {
      проблемы.push(`${c.id}: акцент «${c.accent}» найден в ${попаданий} строках, нужно ровно в одной`);
    }
    // Строка целиком жёлтая — нормально, если в надписи есть и белая часть.
    // Плохо, когда жёлтой оказалась вся надпись: тогда выделять уже нечего.
    if (c.lines.join(' ').trim() === c.accent.trim()) {
      // Правила текста называют это «нельзя», а не «нежелательно» — значит, блокер.
      проблемы.push(`${c.id}: акцентом залита вся надпись — выделять внутри неё уже нечего`);
    }
  }
  // Тип события включает звук автоматически; опечатка в типе — тихо немой вывод.
  const ТИПЫ = ['скриншот','успех','ошибка','уведомление','пометка','акцент'];
  if (c.тип && !ТИПЫ.includes(c.тип)) {
    проблемы.push(`${c.id}: неизвестный тип «${c.тип}» — звук не включится; допустимые: ${ТИПЫ.join(', ')}`);
  }
  const режимНаМомент = режим(c.at);
  const ждём = c.place === 'B-strip' ? 'B' : 'A';
  if (режимНаМомент && режимНаМомент !== ждём) {
    проблемы.push(`${c.id}: place=${c.place} требует режим ${ждём}, а на ${c.at} с идёт ${режимНаМомент}`);
  }
  if (режим(c.until - 0.001) !== режимНаМомент) {
    проблемы.push(`${c.id}: надпись висит на стыке режимов — гаси её до склейки`);
  }
  const максСтрок = c.place === 'B-strip' ? 1 : 2;
  if (c.lines.length > максСтрок) {
    проблемы.push(`${c.id}: строк ${c.lines.length}, для ${c.place} максимум ${максСтрок}`);
  }
  // Тире и прочие одиночные знаки словами не считаем.
  const слов = c.lines.join(' ').split(/\s+/).filter((w) => /[\p{L}\p{N}]/u.test(w)).length;
  if (слов > 5) пометки.push(`${c.id}: ${слов} слов — ТЗ просит 2–5`);

  // Оценка ширины: Oswald в верхнем регистре, начертание 700, межбуквенное 0.015em.
  // Коэффициент 0.58 замерен по отрендеренному кадру — прежние 0.46 занижали на четверть
  // и пропускали строку, которая на экране переносилась на третью.
  const кегль = c.size ?? (c.place === 'B-strip' ? plan.layout.textB.size : plan.layout.textA.size);
  const предел = c.place === 'B-strip' ? plan.layout.textB.width : plan.layout.textA.maxWidth;
  for (const l of c.lines) {
    const ширина = l.length * кегль * 0.58;
    if (ширина > предел) {
      проблемы.push(`${c.id}: строка «${l}» ~${Math.round(ширина)} px, предел ${предел}`);
    } else if (ширина > предел * 0.85) {
      пометки.push(`${c.id}: строка «${l}» близко к пределу (~${Math.round(ширина)} из ${предел})`);
    }
  }
}

for (let i = 1; i < cues.length; i += 1) {
  const пред = cues[i - 1];
  const тек = cues[i];
  if (тек.at < пред.until) {
    проблемы.push(`${пред.id} и ${тек.id}: надписи наложились — в кадре должна быть одна`);
  } else {
    const пауза = тек.at - пред.until;
    if (пауза < MIN_GAP) {
      проблемы.push(`${пред.id} → ${тек.id}: пауза ${пауза.toFixed(2)} с, минимум ${MIN_GAP}`);
    }
  }
}

// Субтитры: генератор держит строку в 26 символов, но после ручной правки
// это некому проверить, кроме нас.
for (const суб of plan.subtitles ?? []) {
  if (!(суб.at < суб.until)) проблемы.push(`субтитр @${суб.at}: at не раньше until`);
  const строка = (суб.words ?? []).map((w) => w.w).join(' ');
  if (строка.length > 30) пометки.push(`субтитр @${суб.at}: ${строка.length} символов — генератор держит 26, строка правлена руками?`);
  for (let i = 1; i < (суб.words ?? []).length; i += 1) {
    if (суб.words[i].t < суб.words[i - 1].t) проблемы.push(`субтитр @${суб.at}: слова не по порядку времени`);
  }
}

// Вырезы: сегменты по возрастанию, без пересечений; надпись, попавшая в вырез
// хоть краем, на экране обрежется молча — это блокер.
const сегменты = (plan.trims ?? []).slice().sort((а, б) => а.from - б.from);
for (let i = 0; i < сегменты.length; i += 1) {
  const с = сегменты[i];
  if (!(с.from < с.to)) проблемы.push(`trims[${i}]: from не раньше to`);
  if (i > 0 && с.from < сегменты[i - 1].to) проблемы.push(`trims[${i}]: пересекается с предыдущим`);
}
if (сегменты.length > 0) {
  const цел = (от, до) => сегменты.some((с) => от >= с.from - 1e-6 && до <= с.to + 1e-6);
  for (const c of cues) {
    if (!цел(c.at, c.until)) проблемы.push(`${c.id}: надпись попадает в вырезанную паузу (trims)`);
  }
  for (const к of plan.zoom?.keys ?? []) {
    if (!сегменты.some((с) => к.at >= с.from - 1e-6 && к.at <= с.to + 1e-6)) {
      пометки.push(`zoom @${к.at}: ключ в вырезанном участке — движение схлопнется в скачок`);
    }
  }
}

// Крупность: канон — references/правила-текста.md скилла, раздел «Крупность»:
// шаг между соседними ключами 6–10 пунктов,
// наездов подряд не больше трёх. Ключ с cut — резкая склейка, шаг у неё не нормируется
// каноном шага (это разрыв, а не движение), но подряд их тоже считаем.
const ключи = (plan.zoom?.keys ?? []).filter((к, i, все) => i === 0 || к.scale !== все[i - 1].scale);
let наездовПодряд = 0;
for (let i = 1; i < ключи.length; i += 1) {
  const шаг = Math.round(Math.abs(ключи[i].scale - ключи[i - 1].scale) * 100);
  if (!ключи[i].cut && (шаг < 6 || шаг > 10)) {
    проблемы.push(`zoom @${ключи[i].at}: шаг ${шаг} пунктов — канон требует 6–10`);
  }
  if (ключи[i].scale > ключи[i - 1].scale) {
    наездовПодряд += 1;
    if (наездовПодряд > 3) проблемы.push(`zoom @${ключи[i].at}: четвёртый наезд подряд — канон разрешает три`);
  } else {
    наездовПодряд = 0;
  }
}


for (const f of plan.fragments ?? []) {
  const внутри = cues.filter((c) => c.until > f.from && c.at < f.to);
  for (const c of внутри.filter((c) => c.at < f.from || c.until > f.to)) {
    проблемы.push(`${c.id}: обрезается границей фрагмента ${f.id} (${f.from}–${f.to})`);
  }
  
console.log(`${f.id}: ${внутри.length} надписей на ${(f.to - f.from).toFixed(1)} с`);
}

for (const e of plan.effects ?? []) {
  const [x, y, w, h] = e.rect;
  if (x < 0 || y < 0 || x + w > plan.width || y + h > plan.height) {
    проблемы.push(`замазка ${e.from}–${e.to}: rect выходит за кадр`);
  }
  if (e.to - e.from <= 0) проблемы.push(`замазка ${e.from}–${e.to}: пустое окно`);
  // Скринкаст виден только в режиме сплита — замазка вне него закроет пустоту.
  if (plan.modes?.length && (режим(e.from) !== 'B' || режим(e.to - 0.001) !== 'B')) {
    проблемы.push(`замазка ${e.from}–${e.to}: окно выходит за пределы режима B`);
  }
}

for (const p of plan.приватность ?? []) {
  if (String(p.статус).startsWith('НЕ закрыто')) {
    пометки.push(`приватность ${p.from}–${p.to} с: ${p.что} — ${p.статус}`);
  }
}

if (пометки.length) {
  console.log('\nПометки (решает человек):');
  for (const m of пометки) console.log(`  · ${m}`);
}

if (проблемы.length) {
  console.log('\nНарушения ТЗ:');
  for (const p of проблемы) console.log(`  ✗ ${p}`);
  process.exit(1);
}

console.log('\nЧеклист пройден.');
