import plan from '../edit-plan.json';

/** Сегмент исходника, который ОСТАВЛЯЕМ: [от, до] в секундах источника. */
export type Сегмент = { from: number; to: number };

type ПланВырезов = { trims?: Сегмент[] };

/**
 * Пересчёт времени после вырезания пауз.
 *
 * Лист хранит «trims» — список сегментов исходника, которые остаются в выходе,
 * по возрастанию и без пересечений. Все остальные разделы листа (cues, subtitles,
 * zoom, effects) продолжают жить в секундах ИСХОДНИКА — пересчёт в выходное время
 * делает этот модуль, и только он. Нет раздела — тождественное отображение,
 * ничего не вырезано.
 */
const ВЫРЕЗЫ: Сегмент[] = ((plan as ПланВырезов).trims ?? []).slice()
  .sort((а, б) => а.from - б.from);

const активны = ВЫРЕЗЫ.length > 0;

/** Сегменты, пересечённые с окном фрагмента [from, to]. */
export const сегментыФрагмента = (from: number, to: number): Сегмент[] => {
  if (!активны) return [{ from, to }];
  return ВЫРЕЗЫ
    .map((с) => ({ from: Math.max(с.from, from), to: Math.min(с.to, to) }))
    .filter((с) => с.to - с.from > 1e-6);
};

/** Длительность выхода для окна фрагмента, в секундах. */
export const выходнаяДлительность = (from: number, to: number): number =>
  сегментыФрагмента(from, to).reduce((н, с) => н + (с.to - с.from), 0);

/** Секунда исходника → секунда выхода (внутри окна фрагмента). Для точки в вырезе — начало следующего сегмента. */
export const вВыход = (срс: number, from: number, to: number): number => {
  let накоплено = 0;
  for (const с of сегментыФрагмента(from, to)) {
    if (срс < с.from) return накоплено;
    if (срс <= с.to) return накоплено + (срс - с.from);
    накоплено += с.to - с.from;
  }
  return накоплено;
};

/** Секунда выхода → секунда исходника (внутри окна фрагмента). */
export const вИсходник = (вых: number, from: number, to: number): number => {
  let накоплено = 0;
  const список = сегментыФрагмента(from, to);
  for (const с of список) {
    const длина = с.to - с.from;
    if (вых <= накоплено + длина) return с.from + (вых - накоплено);
    накоплено += длина;
  }
  const последний = список[список.length - 1];
  return последний ? последний.to : to;
};

/** Попадает ли отрезок исходника целиком в оставленное (не задет ли вырезом). */
export const цел = (от: number, до: number): boolean => {
  if (!активны) return true;
  return ВЫРЕЗЫ.some((с) => от >= с.from - 1e-6 && до <= с.to + 1e-6);
};
